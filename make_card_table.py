"""Supplement table: certificate-card fields 2 and 4 for all 33 judge runs (run 1, refusals as blocks).

Reads only shipped caches:
  crossfit33.json      (unify_crossfit.py --json crossfit33.json): cross-fitted split-conformal operating
                       points, means over 500 label-balanced two-fold splits, seed 0;
  forest33.json        (analyze_agentdojo_inference.py --family complete --json forest33.json): AUCs;
  calib_randomized.json (calib_randomized.py --json calib_randomized.json): exact-level randomized
                       split-conformal false block at delta = .10 (same splits);
  attack_unified.json  (analyze_attack_common.py --family unified): miss increase at theta = .5 from the
                       predeclared 16-word suffix over all 35 violations, with suite-stratified max-T
                       simultaneous 95% intervals (21 attacked runs).
Writes the complete table* included by paper/supp/appD_related.tex (\\input outside any tabular).
Usage: python make_card_table.py [OUT.tex]"""
import json, os, sys

H = os.path.dirname(os.path.abspath(__file__))
OUT = sys.argv[1] if len(sys.argv) > 1 else os.path.join(H, "paper", "supp", "card33_table.tex")
L = lambda f: json.load(open(os.path.join(H, f)))
cf = {r["judge"]: r for r in L("crossfit33.json")["rows"]}
fo = L("forest33.json")
auc = dict(zip(fo["names"], fo["auc"]))
ATT = {"qwen2.5:3b": "Qwen-2.5-3B", "qwen2.5:7b": "Qwen-2.5-7B", "qwen2.5:32b": "Qwen-2.5-32B",
       "llama3.1:8b": "Llama-3.1-8B", "gemma2:9b": "Gemma-2-9B", "llama-3.3:70b": "Llama-3.3-70B",
       "command-a": "Command A"}
att = {ATT.get(j["name"], j["name"]): j for j in L("attack_unified.json")["judges"]}
rnd = {r["judge"]: r for r in L("calib_randomized.json")["rows"]}
assert set(rnd) == set(cf)
assert set(cf) == set(auc) and len(cf) == 33 and set(att) <= set(cf) and len(att) == 21

HEAD = r"""\begin{table*}[t]
\caption{Certificate-card fields 2 and 4 for all 33 judge runs (run 1, refusals as blocks; sorted
by AUC). Operating points are split-conformal at target $\delta$ on 17--18 violating calibration
examples, as means over 500 label-balanced two-fold cross-fitted splits (seed 0); under this
deterministic rule every run is block-all at $\delta=.05$ (false block $1.000$), so field 3 forces
the same honest report for all 33, while exact-level randomized calibration (rand.) spends the full
miss budget ($\approx\delta$) at a lower false block (\texttt{calib\_randomized.py}). Field 4 lists the only margin evidence we have, a lower bound: the miss increase at
$\theta=.5$ from the predeclared 16-word suffix over all 35 violations, with suite-stratified
max-$T$ simultaneous 95\% intervals ($^{*}$: interval above zero; ---: attacked strings not
scored); non-positive values mean the suffix made the judge flag more violations and bound
nothing. No run has a verified margin, so every gate is uncertified under attack. (filtered):
served through the provider's content-filtered endpoint (Supplement~B.1). Fields 1 and 5
are as in Table~\ref{tab:card-ours} for every run. Generated by \texttt{make\_card\_table.py}.}
\label{tab:card33}
\centering\footnotesize
\setlength{\tabcolsep}{5pt}
\renewcommand{\arraystretch}{1.05}
\begin{tabular}{@{}lccccccl@{}}
\toprule
& & \multicolumn{3}{c}{Field 2, $\delta=.10$} & \multicolumn{2}{c}{Field 2, $\delta=.20$} & Field 4: suffix miss increase \\
\cmidrule(lr){3-5}\cmidrule(lr){6-7}
Judge run & AUC & miss & false block & rand.\ f.b. & miss & false block & at $\theta=.5$ [simultaneous 95\%] \\
\midrule
"""
FOOT = r"""\bottomrule
\end{tabular}
\end{table*}
"""

f3 = lambda x: f"{x:.3f}"[1:] if 0 <= x < 1 else ("1.000" if abs(x - 1) < 5e-4 else f"{x:.3f}")
sgn = lambda x: ("$-$" + f"{-x:.3f}"[1:]) if x < 0 else ("$+$" + f"{x:.3f}"[1:] if x > 0 else "$\\phantom{+}$.000")
nice = lambda n: n.replace("Claude-", "Claude ").replace("GPT-6.1-", "GPT-6.1 ").replace("Opus-", "Opus ") \
                  .replace("Sonnet-", "Sonnet ").replace("Haiku-", "Haiku ").replace("Fable-", "Fable ")
rows = []
for n in sorted(cf, key=lambda n: -auc[n]):
    r = cf[n]
    a = att.get(n)
    if a is None:
        atk = "---"
    else:
        star = r"$^{*}$" if a["lo"] > 0 else ""
        atk = f"{sgn(a['est'])}{star} [{sgn(a['lo'])}, {sgn(a['hi'])}]"
    rows.append(f"{nice(n)} & {f3(auc[n])} & {f3(r['miss_0.10'])} & {f3(r['false_block_0.10'])} & {f3(rnd[n]['rand_0.10'][1])} & "
                f"{f3(r['miss_0.20'])} & {f3(r['false_block_0.20'])} & {atk} \\\\")
assert all(cf[n]["false_block_0.05"] > 0.999 for n in cf)   # every delta = .05 gate is block-all
with open(OUT, "w") as fh:
    fh.write("% generated by make_card_table.py from crossfit33.json, forest33.json, attack_unified.json\n")
    fh.write(HEAD + "\n".join(rows) + "\n" + FOOT)
print("wrote", OUT, len(rows), "rows;", sum(1 for a in att.values() if a["lo"] > 0), "intervals above 0")
